const {chromium} = require('playwright');
const fs=require('fs');
(async()=>{
 const path=require('path');
 const root=path.resolve(__dirname,'..');
 const stateDir=path.resolve(process.env.FACTORY_BROWSER_STATE||path.join(root,'.local/dashboard-qa'));
 const base=process.env.FACTORY_BROWSER_URL||'http://127.0.0.1:8097';
 if(!['127.0.0.1','localhost','[::1]'].includes(new URL(base).hostname)) throw Error('Browser QA permits loopback only');
 const token=fs.readFileSync(stateDir+'/operator-1.token','utf8').trim();
 const qa=JSON.parse(fs.readFileSync(stateDir+'/qa.json','utf8'));
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/');
 await page.getByLabel('Access token').fill(token);
 await page.getByRole('button',{name:'Connect / refresh',exact:true}).click();
 await page.getByText('Application evidence',{exact:true}).waitFor();
 await page.getByRole('button',{name:'Research',exact:true}).click();
 await page.getByRole('heading',{name:'Research activity'}).waitFor();
 await page.getByRole('button',{name:'Improvements',exact:true}).click();
 await page.getByRole('heading',{name:'Controlled training improvement'}).waitFor();
 await page.getByLabel('Research region').selectOption(qa.protocol_hash);
 await page.getByLabel('Maximum parent plans').fill('1');
 await page.getByLabel('Children per parent').fill('2');
 await page.getByRole('button',{name:'Enable bounded improvement',exact:true}).click();
 await page.getByRole('button',{name:'Stop new children',exact:true}).waitFor();
 await page.screenshot({path:root+'/reports/runtime/improvement-browser-desktop.png',fullPage:true});
 const state=await (await page.request.get(base+'/api/v1/improvement/status',{headers:{Authorization:'Bearer '+token}})).json();
 if(state.policies.length!==1||!state.paused||state.plans!==0)throw Error('Policy registration changed pause or invented plans');
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:root+'/reports/runtime/improvement-browser-mobile.png',fullPage:true});
 const overflow=await page.evaluate(()=>({document:document.documentElement.scrollWidth,viewport:innerWidth}));
 await page.getByRole('button',{name:'Stop new children',exact:true}).click();
 await page.getByRole('button',{name:'Stop new children',exact:true}).waitFor({state:'detached'});
 await page.getByRole('button',{name:'Queue',exact:true}).click();
 await page.getByRole('button',{name:'Cancel job',exact:true}).click();
 await page.getByText(qa.job_id.slice(0,12)+' · CANCELLED',{exact:true}).waitFor();
 if(errors.length)throw Error('Browser page errors: '+errors.join(';'));
 if(overflow.document>overflow.viewport)throw Error('Mobile horizontal overflow');
 const report={source:qa.source,scope:'real loopback API + Chromium, synthetic paused state; not full C7 acceptance',status:'PASS',browser:await browser.version(),checks:['authenticated overview','live research counts','register bounded improvement policy','pause preserved','disable policy','cancel queued job','no page exceptions'],mobile:overflow};
 fs.writeFileSync(root+'/reports/runtime/improvement-browser.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify(report));await browser.close();
})().catch(e=>{console.error(e.message);process.exit(1)});
